<?php

declare(strict_types=1);

namespace VmEngine\Synapse\Notifications;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\Schema;
use VmEngine\SynAuth\Models\Role;

class NotificationSetup
{
    /**
     * Whether the optional vm-engine/synapps-auth package is installed.
     * Role-targeting and the notification setup flow both depend on it.
     */
    public static function authInstalled(): bool
    {
        return class_exists(Role::class);
    }

    /**
     * Whether the stock `notifications` table already exists.
     */
    public static function tableReady(): bool
    {
        return Schema::hasTable('notifications');
    }

    /**
     * Publish the framework's notifications:table migration, but only if no
     * migration file already creates the table (avoids duplicate-table
     * migration errors on a project that already has one, generated by a
     * previous manual `php artisan notifications:table` run).
     */
    public static function ensureMigration(Command $command): void
    {
        $existing = glob(database_path('migrations/*_create_notifications_table.php'));

        if (empty($existing)) {
            $command->call('notifications:table');
        }
    }
}
